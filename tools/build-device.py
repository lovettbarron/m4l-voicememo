#!/usr/bin/env python3
"""Generate device/VoiceMemo.amxd and the scripts beside it from src/.

Max finds scripts in the device's own folder, so the patch names them by file name only:
no absolute paths, and the device works from any checkout. Keep device/ inside the repo:
voicememo-core.js loads the Node code from ../src.
"""
import json
import os
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
OUT = os.path.join(ROOT, "device", "VoiceMemo.amxd")

def p(*parts):
    return os.path.join(SRC, *parts)

DEVICE = os.path.dirname(OUT)
os.makedirs(DEVICE, exist_ok=True)
GENERATED = "// GENERATED by tools/build-device.py from {} - do not edit.\n"
def emit(name, body, origin):
    with open(os.path.join(DEVICE, name), "w") as f:
        f.write(GENERATED.format(origin) + body)
    return name

# jsui include() resolves through Max's search path, so inline theme.js into self-contained copies.
THEME = open(p("ui", "theme.js")).read()
def ui(src_name, name):
    body = open(p("ui", src_name)).read().replace("include('theme.js');\n", THEME + "\n")
    return emit(name, body, "src/ui/" + src_name)

# Unique names so nothing else on Max's search path can shadow them.
CORE = emit("voicememo-core.js", "'use strict';\nrequire(require('path').join(__dirname, '..', 'src', 'max', 'vm-core.js'));\n",
            "src/max/vm-core.js (loader)")
LOM = emit("voicememo-lom.js", open(p("max", "lom-bridge.js")).read(), "src/max/lom-bridge.js")
LIST, WAVE, PANEL = ui("memo-list.js", "voicememo-list.js"), ui("wave-view.js", "voicememo-wave.js"), ui("window-panel.js", "voicememo-panel.js")

boxes, lines = [], []

def obj(id, boxtext, rect, ins=1, outs=1, cls="newobj", pres=None, **kw):
    b = {"id": id, "maxclass": cls, "numinlets": ins, "numoutlets": outs, "patching_rect": rect}
    if boxtext is not None:
        b["text"] = boxtext
    if pres:
        b["presentation"] = 1
        b["presentation_rect"] = pres
    b.update(kw)
    boxes.append({"box": b})
    return id

def wire(src, dst, so=0, di=0):
    lines.append({"patchline": {"source": [src, so], "destination": [dst, di]}})

def param(longname, shortname, ptype, **extra):
    v = {"parameter_longname": longname, "parameter_shortname": shortname, "parameter_type": ptype}
    v.update(extra)
    return {"saved_attribute_attributes": {"valueof": v}, "parameter_enable": 1}

