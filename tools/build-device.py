obj("resendmsg", None, [70, 335, 55, 22], cls="message", text="resend", ins=2)
obj("print", "print voicememo", [940, 300, 100, 22], outs=0)

wire("thisdev", "one"); wire("one", "metro"); wire("thisdev", "lominit"); wire("lominit", "lomjs")
wire("metro", "lomjs"); wire("lomjs", "node")
wire("node", "route")
wire("route", "readyt", 0)
wire("readyt", "initmsg", 3); wire("initmsg", "node")
wire("readyt", "resendmsg", 2); wire("resendmsg", "lomjs")
wire("route", "print", 18)

